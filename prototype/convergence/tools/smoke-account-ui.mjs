import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright-core');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4191/?qa=1',{waitUntil:'domcontentloaded'});
await page.waitForSelector('#account-btn',{state:'attached',timeout:25000});
assert.equal(await page.locator('#account-btn').isHidden(),true);
await page.evaluate(()=>window.__convergence.accountPortal.open());
await page.waitForSelector('#account-portal:not(.hidden)');
const text=await page.locator('#account-methods').textContent();
assert.match(text,/non configurée/);
assert.equal(await page.locator('#player-alias').count(),1);
await page.goto('http://127.0.0.1:4191/cockpit.html',{waitUntil:'domcontentloaded'});
assert.equal(await page.locator('#signin').isDisabled(),true);
assert.equal(errors.length,0,JSON.stringify(errors));
console.log(JSON.stringify({mobile:390,accountPanel:true,cockpitProtected:true,errors},null,2));
await browser.close();