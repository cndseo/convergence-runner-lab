import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
const {chromium}=createRequire(import.meta.url)('playwright-core');
const url=process.env.QA_URL||'http://127.0.0.1:4729/';
const out=new URL('../../../qa-first-tv-20261022/',import.meta.url);
mkdirSync(out,{recursive:true});
const file=n=>new URL(n,out).pathname.replace(/^\/([A-Za-z]:)/,'$1');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const report={url,checks:[],errors:[],badAssets:[]};
try{
 const ctx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await ctx.route('**/api/v1/**',r=>r.fulfill({json:{leaderboard:false,payments:'disabled'}}));
 const page=await ctx.newPage();
 page.on('pageerror',e=>report.errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400&&r.url().includes('/assets/'))report.badAssets.push(r.status()+' '+r.url());});
 await page.goto(url+'?qa=1',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>window.__convergence?.tvChoice?.tutorial,{timeout:20000});
 const reset=async(level=1,distance=10)=>{
  await page.evaluate(({level,distance})=>{
   const g=window.__convergence;
   g.heroes.needsChoice=()=>false;g.ui.hideAllScreens();g.mode='campaign';g.parisJourney.playDistrict(level);
   g.parisJourney.card.classList.remove('visible');g.trackZ=g.levelGenerator.gates[0].z-distance;
   g.levelGenerator.updateVisibility(g.trackZ);
   g.crowdManager.updatePlayerPosition(g.playerX,-g.trackZ);
   g.marchCameraDistance=g.crowdManager.getCameraDistance();
   g.camera.position.set(g.playerX*.3,g.crowdManager.getCameraHeight(),-g.trackZ+g.marchCameraDistance);
   g.camera.lookAt(g.playerX*.3,.8,-g.trackZ-5);
   g.update(.10);g.renderer.render(g.scene,g.camera);
  },{level,distance});
 };
 const visible=()=>page.locator('#first-tv-tutorial:visible').count();
 const targets=()=>page.evaluate(()=>{
  const g=window.__convergence;
  return g.tvChoice.targets().map(t=>({side:t.side,x:t.x,y:t.y,left:t.left,right:t.right,top:t.top,bottom:t.bottom}));
 });
 await reset(1,25);
 assert.equal(await visible(),0,'Nothing before TV interaction range');
 await reset(1,9);
 assert.equal(await visible(),1,'Prominent tutorial appears before first pair');
 assert.equal((await page.locator('.first-tv-callout').innerText()),'🤛 CHOISIS 1 TV 🤜');
 const t=await targets();
 assert.equal(t.length,2);
 assert.equal(await page.locator('.first-tv-marker').count(),2);
 const metrics=await page.evaluate(()=>{
  const el=document.querySelector('#first-tv-tutorial'),canvas=document.querySelector('#game-canvas');
  const bar=el.querySelector('.first-tv-callout').getBoundingClientRect();
  return {pointerEvents:getComputedStyle(el).pointerEvents,barHeight:bar.height,barWidth:bar.width,viewportWidth:innerWidth,barTop:bar.top,canvasElement:document.elementFromPoint(innerWidth*.2,innerHeight*.7)===canvas};
 });
 assert.equal(metrics.pointerEvents,'none');
 assert.ok(metrics.barWidth<=391&&metrics.barHeight>=35);
 report.checks.push({test:'in-road-mobile-visual-before-first-TV',metrics});
 await page.screenshot({path:file('tutorial-visible-iphone-390.png')});
 const tapped=t[0];
 await page.touchscreen.tap((tapped.left+tapped.right)/2,(tapped.top+tapped.bottom)/2);
 assert.equal(await visible(),0,'Tutorial disappears on first TV tap');
 let result=await page.evaluate(()=>{const g=window.__convergence;return {side:g.gateHistory[0]?.side,done:g.tvChoice.tutorial.done,history:g.gateHistory.length,state:g.state}});
 assert.equal(result.side,'left');assert.equal(result.history,1);
 report.checks.push({test:'tap-left-removes-tutorial-and-selects-only-left',...result});
 await page.evaluate(()=>{const g=window.__convergence;g.update(.10)});
 assert.equal(await visible(),0,'Does not reappear after first TV');
 await reset(1,9);
 assert.equal(await visible(),1,'New run resets first TV tutorial');
 const right=(await targets()).find(t=>t.side==='right');
 await page.touchscreen.tap((right.left+right.right)/2,(right.top+right.bottom)/2);
 assert.equal(await visible(),0,'Touching the right TV also dismisses tutorial');
 assert.equal(await page.evaluate(()=>window.__convergence.gateHistory[0]?.side),'right');
 report.checks.push({test:'tap-right-removes-tutorial',ok:true});
 await reset(1,9);
 await page.evaluate(()=>{const g=window.__convergence;g.trackZ=g.levelGenerator.gates[0].z-0.8;g.checkGateCollisions();g.tvChoice.update(.1)});
 assert.equal(await visible(),0,'Miss removes tutorial');
 result=await page.evaluate(()=>{const g=window.__convergence;return {outcome:g.gateHistory[0]?.side,done:g.tvChoice.tutorial.done}});
 assert.equal(result.outcome,'miss');
 report.checks.push({test:'miss-applies-existing-damage-and-removes-tutorial',...result});
 await reset(2,9);
 assert.equal(await visible(),0,'Tutorial level one only');
 await reset(1,9);
 await page.locator('#pause-btn').click();
 await page.evaluate(()=>window.__convergence.tvChoice.update(.1));
 assert.equal(await visible(),0,'Pause hides tutorial');
 await page.locator('#resume-btn').click();
 await page.evaluate(()=>window.__convergence.tvChoice.update(.1));
 assert.equal(await visible(),1,'Resume shows same TV tutorial');
 report.checks.push({test:'no-level-two-or-pause-overlay-regression',ok:true});
 assert.deepEqual(report.errors,[]);
 assert.deepEqual(report.badAssets,[]);
 writeFileSync(file('results.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({ok:true,...report}));
}finally{await browser.close();}
