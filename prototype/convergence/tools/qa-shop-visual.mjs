import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
const require=createRequire(import.meta.url),{chromium}=require('playwright-core');
const base=process.env.QA_URL||'http://127.0.0.1:4719/';
const dir=new URL('../../../qa-shop-visual/',import.meta.url);
mkdirSync(dir,{recursive:true});
const file=n=>new URL(n,dir).pathname.replace(/^\/([A-Za-z]:)/,'$1');
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--enable-webgl','--ignore-gpu-blocklist']});
const report={url:base,errors:[],badAssets:[],checks:[]};
try{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
 await context.route('**/api/v1/**',r=>r.fulfill({json:{leaderboard:false,payments:'disabled'}}));
 const page=await context.newPage();
 page.on('pageerror',e=>report.errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400&&r.url().includes('/assets/'))report.badAssets.push(r.status()+' '+r.url());});
 await page.goto(base+'?qa=1',{waitUntil:'networkidle'});
 await page.waitForSelector('#premium-btn');
 await page.locator('#premium-btn').click();
 assert.equal(await page.locator('#challenge-hub.shop-mode:not(.hidden)').count(),1);
 assert.equal(await page.locator('.challenge-product').count(),7);
 assert.equal(await page.locator('.shop-product-art').count(),7);
 assert.equal(await page.locator('.shop-categories button').count(),4);
 assert.equal(await page.locator('.shop-kicker:visible').count(),1);
 report.checks.push('Seven products, four colorful categories and storefront header');
 const audit=await page.evaluate(()=>{
  const panel=document.querySelector('#challenge-hub .challenge-card'),rect=panel.getBoundingClientRect();
  const rows=[...panel.querySelectorAll('.challenge-product')];
  return {window:innerWidth,card:{x:rect.x,width:rect.width,right:rect.right},
   scrollWidth:panel.scrollWidth,clientWidth:panel.clientWidth,
   products:rows.map(r=>({sku:r.dataset.product,price:r.querySelector('button')?.textContent,disabled:r.querySelector('button')?.disabled}))};
 });
 assert.ok(audit.card.right<=391&&audit.card.x>=-1);
 assert.equal(audit.scrollWidth,audit.clientWidth,'Horizontal overflow in shop');
 assert.deepEqual(audit.products.slice(0,2).map(item=>item.sku),['genz3','genz12'],'GenZ featured products must lead the catalogue');
 report.mobile390=audit;
 await page.screenshot({path:file('shop-390-header.png')});
 await page.locator('.challenge-card').evaluate(e=>e.scrollTop=e.scrollHeight);
 await page.screenshot({path:file('shop-390-footer.png')});
 await page.locator('.shop-categories button:nth-child(2)').click();
 assert.equal(await page.locator('.challenge-product').count(),2);
 assert.equal(await page.locator('.shop-available').count(),2);
 report.checks.push('GenZ category filters exactly two SKUs, stock counts preserved');
 await page.locator('.shop-categories button:nth-child(3)').click();
 assert.equal(await page.locator('.challenge-product').count(),3);
 await page.locator('.shop-categories button:nth-child(4)').click();
 assert.equal(await page.locator('.challenge-product').count(),2);
 await page.locator('.shop-categories button:nth-child(1)').click();
 assert.equal(await page.locator('.challenge-product').count(),7);
 report.checks.push('All, GenZ, Marseille and Costumes filters work');
 await page.setViewportSize({width:320,height:700});
 await page.locator('.challenge-card').evaluate(e=>e.scrollTop=0);
 const small=await page.evaluate(()=>{const e=document.querySelector('.challenge-card'),r=e.getBoundingClientRect();return {x:r.x,width:r.width,right:r.right,scroll:e.scrollWidth,client:e.clientWidth}});
 assert.ok(small.x>=-1&&small.right<=321);
 assert.equal(small.scroll,small.client,'Overflow on narrow iPhone');
 report.mobile320=small;
 await page.screenshot({path:file('shop-320.png')});
 await page.locator('.challenge-close').click();
 assert.equal(await page.locator('#challenge-hub.shop-mode:not(.hidden)').count(),0);
 await page.locator('#daily-btn').click();
 assert.equal(await page.locator('#challenge-hub.shop-mode').count(),0);
 assert.equal(await page.locator('.shop-kicker:visible').count(),0);
 report.checks.push('Close shop and return to Daily without shop skin');
 await page.locator('.challenge-close').click();
 await page.locator('#premium-btn').click();
 await page.getByRole('button',{name:/TESTER 3 TIRS GENZ/}).click();
 const ammo=await page.evaluate(()=>window.__convergence?.genzFireworks?.demoCharges);
 assert.equal(ammo,3);
 report.checks.push('Demo action unchanged: 3 GenZ shots granted');
 assert.deepEqual(report.errors,[]);
 assert.deepEqual(report.badAssets,[]);
 writeFileSync(file('report.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({ok:true,...report}));
}finally{await browser.close();}
